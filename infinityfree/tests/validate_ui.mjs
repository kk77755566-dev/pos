import fs from "node:fs";
const html=fs.readFileSync(new URL("../index.php",import.meta.url),"utf8");
const client=fs.readFileSync(new URL("../pos.js",import.meta.url),"utf8");
const ids=[...html.matchAll(/id="([^"]+)"/g)].map(m=>m[1]);
const duplicates=ids.filter((id,i)=>ids.indexOf(id)!==i);
const available=new Set(ids);
const used=[...client.matchAll(/\$\('([^']+)'\)/g)].map(m=>m[1]);
const missing=[...new Set(used.filter(id=>!available.has(id)))];
if(duplicates.length)throw new Error("Duplicate UI IDs: "+duplicates.join(", "));
if(missing.length)throw new Error("POS client references missing UI IDs: "+missing.join(", "));
console.log("InfinityFree POS UI element bindings: OK");
